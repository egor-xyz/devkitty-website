import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import type { Plugin } from 'vite';

import { type Extension, parseExtension } from '../src/lib/extensionSchema';

const SITE = 'https://devkitty.app';
const MARKER = '<!-- generated by scripts/extensionsPlugin.ts: do not edit -->';

const escapeHtml = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

const STATUS_LABEL: Record<Extension['status'], string> = {
  beta: 'Beta',
  'coming-soon': 'Coming soon',
  new: 'New',
  stable: 'Stable'
};

/** Reads and validates every `src/content/extensions/*.json`; throws on the first problem, naming the file. */
export function loadExtensions(root: string): Extension[] {
  const dir = join(root, 'src/content/extensions');
  const files = readdirSync(dir)
    .filter((f) => f.endsWith('.json'))
    .sort();

  const list = files.map((file) => {
    let raw: unknown;
    try {
      raw = JSON.parse(readFileSync(join(dir, file), 'utf8'));
    } catch (e) {
      throw new Error(`${file}: invalid JSON (${(e as Error).message})`);
    }

    const ext = parseExtension(raw, file);
    if (`${ext.id}.json` !== file) throw new Error(`${file}: id must equal the file name`);

    const assets = [ext.icon, ...ext.screenshots.map((s) => s.src)];
    for (const asset of assets) {
      if (!existsSync(join(root, 'public', asset))) throw new Error(`${file}: ${asset} does not exist under public/`);
    }

    return ext;
  });

  return list.sort((a, b) => a.order - b.order || a.name.localeCompare(b.name));
}

function writePages(root: string, list: Extension[]): void {
  const base = join(root, 'extensions');
  const template = readFileSync(join(base, '_page.html'), 'utf8');
  const ids = new Set(list.map((e) => e.id));

  // Remove pages of deleted extensions (only folders this plugin generated).
  for (const entry of readdirSync(base, { withFileTypes: true })) {
    const page = join(base, entry.name, 'index.html');
    if (entry.isDirectory() && !ids.has(entry.name) && existsSync(page) && readFileSync(page, 'utf8').includes(MARKER)) {
      rmSync(join(base, entry.name), { force: true, recursive: true });
    }
  }

  for (const ext of list) {
    const og = ext.screenshots[0]?.src ?? '/og.png';
    const prerender = `<main style="max-width:820px;margin:0 auto;padding:72px 16px"><h1>${escapeHtml(ext.name)}</h1><p>${escapeHtml(ext.tagline)}</p><p>${STATUS_LABEL[ext.status]}</p></main>`;
    const html = template
      .replaceAll('%EXT_ID%', escapeHtml(ext.id))
      .replaceAll('%EXT_NAME%', escapeHtml(ext.name))
      .replaceAll('%EXT_TAGLINE%', escapeHtml(ext.tagline))
      .replaceAll('%EXT_OG%', escapeHtml(og))
      .replaceAll('%EXT_PRERENDER%', prerender);

    mkdirSync(join(base, ext.id), { recursive: true });
    writeFileSync(join(base, ext.id, 'index.html'), `${MARKER}\n${html}`);
  }
}

function indexList(list: Extension[]): string {
  const items = list.map((e) => `<li><a href="/extensions/${escapeHtml(e.id)}/">${escapeHtml(e.name)}</a>: ${escapeHtml(e.tagline)}</li>`);

  return `<main style="max-width:820px;margin:0 auto;padding:72px 16px"><h1>Extensions</h1><ul>${items.join('')}</ul></main>`;
}

export function extensionsPlugin(): Plugin {
  let root = process.cwd();
  let list: Extension[] = [];

  return {
    config(userConfig) {
      root = resolve(userConfig.root ?? process.cwd());
      list = loadExtensions(root);
      writePages(root, list);

      const input: Record<string, string> = { 'ext-index': 'extensions/index.html' };
      for (const ext of list) input[`ext-${ext.id}`] = `extensions/${ext.id}/index.html`;

      return { build: { rolldownOptions: { input } } };
    },

    configureServer(server) {
      const dir = join(root, 'src/content/extensions');
      const regenerate = (file: string) => {
        if (!file.startsWith(dir) || !file.endsWith('.json')) return;
        try {
          list = loadExtensions(root);
          writePages(root, list);
          server.ws.send({ type: 'full-reload' });
        } catch (e) {
          server.config.logger.error(`extensions: ${(e as Error).message}`);
        }
      };
      server.watcher.add(dir);
      server.watcher.on('add', regenerate);
      server.watcher.on('change', regenerate);
      server.watcher.on('unlink', regenerate);
    },

    generateBundle() {
      const date = new Date().toISOString().slice(0, 10);
      const paths = ['/', '/privacy/', '/terms/', '/extensions/', ...list.map((e) => `/extensions/${e.id}/`)];
      const urls = paths.map((p) => `  <url>\n    <loc>${SITE}${p}</loc>\n    <lastmod>${date}</lastmod>\n  </url>`).join('\n');

      this.emitFile({
        fileName: 'sitemap.xml',
        source: `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls}\n</urlset>\n`,
        type: 'asset'
      });
    },

    name: 'devkitty-extensions',

    transformIndexHtml: {
      handler(html, ctx) {
        if (!ctx.filename.endsWith('/extensions/index.html')) return html;

        return html.replace('%EXT_LIST%', indexList(list));
      },
      order: 'pre'
    }
  };
}
